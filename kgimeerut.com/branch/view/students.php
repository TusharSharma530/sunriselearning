				<h3>Rules & Regulations</h3>
				<h4>RAGGING is a CRIMINAL offense.</h4>
				<p>It is mandatory for all students to fill the <strong>Anti ragging Affidavit</strong> issued by  UPTU and AICTE at the time of admission.</p>
			</div>
			<div class="studentdesc">
				<h3>What constitutes Ragging?</h3>
				<p>Ragging constitutes one or more of any of the following acts</p>
				<ul>
					<li><i class="ri-graduation-cap-fill"></i> Any conduct by any student or students whether by words spoken or written or by an act which has the effect of teasing, treating or handling with rudeness a fresher or any other student;</li>
					<li><i class="ri-graduation-cap-fill"></i> Indulging in rowdy or undisciplined activities by any student or students which causes or is likely to cause annoyance, hardship, physical or psychological harm or to raise fear or apprehension thereof in any fresher or any other student;</li>
					<li><i class="ri-graduation-cap-fill"></i> Asking any student to do any act which such student will not in the ordinary course do and which has the effect of causing or generating a sense of shame, or torment or embarrassment so as to adversely affect the physique or psyche of such fresher or any other student;</li>
					<li><i class="ri-graduation-cap-fill"></i> Any act by a senior student that prevents, disrupts or disturbs the regular academic activity of any other student or a fresher;</li>
					<li><i class="ri-graduation-cap-fill"></i> Exploiting the services of a fresher or any other student for completing the academic tasks assigned to an individual or a group of students;</li>
					<li><i class="ri-graduation-cap-fill"></i> Any act of financial extortion or forceful expenditure burden put on a fresher or any other student by students;</li>
					<li><i class="ri-graduation-cap-fill"></i> Any act of physical abuse including all variants of it: sexual abuse, homosexual assaults, stripping, forcing obscene and lewd acts, gestures, causing bodily harm or any other danger to health or person;</li>
					<li><i class="ri-graduation-cap-fill"></i> Any act or abuse by spoken words, emails, posts, public insults which would also include deriving perverted pleasure, vicarious or sadistic thrill from actively or passively participating in the discomfiture to fresher or any other student;</li>
					<li><i class="ri-graduation-cap-fill"></i> Any act that affects the mental health and self-confidence of a fresher or any other student with or without an intent to derive a sadistic pleasure or showing off power, authority or superiority by a student over any fresher or any other student.					</li>
				</ul>
			</div>

			<div class="studentdesc">
				<h3>Punishment for Culprits</h3>
				<p>KGI, Meerut shall consider one or more of the following punishments for students involved in ragging</p>
				<ul>					
					<li><i class="ri-graduation-cap-fill"></i>Cancellation of admission	</li>
					<li><i class="ri-graduation-cap-fill"></i>Suspension from attending classes	</li>
					<li><i class="ri-graduation-cap-fill"></i>Withholding/withdrawing scholarship/fellowship and other benefits	</li>
					<li><i class="ri-graduation-cap-fill"></i>Debarring from appearing in any test/examination or other evaluation process	</li>
					<li><i class="ri-graduation-cap-fill"></i>Withholding results	</li>
					<li><i class="ri-graduation-cap-fill"></i>Debarring from representing the institution in any regional, national or international meet, tournament, youth festival, etc.	</li>
					<li><i class="ri-graduation-cap-fill"></i>Suspension/expulsion from the hostel	</li>
					<li><i class="ri-graduation-cap-fill"></i>Rustication from the institution for period ranging from 1 to 4 semesters	</li>
					<li><i class="ri-graduation-cap-fill"></i>Expulsion from the institution and consequent debarring from admission to any other institution	</li>
					<li><i class="ri-graduation-cap-fill"></i>Lodging of an FIR with the police	</li>
					<li><i class="ri-graduation-cap-fill"></i>Monetary penalty of up to Rs. 50,000/- (Rs. Fifty Thousand)	</li>
					<li><i class="ri-graduation-cap-fill"></i>Collective punishment: when the persons committing or abetting the crime of ragging are not identified, the institution shall resort to collective punishment as a deterrent to ensure community pressure on the potential raggers.	</li>
				</ul>
